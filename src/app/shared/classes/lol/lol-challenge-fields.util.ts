/**
 * Human-readable French label for a `LoLGameParticipantChallenges` field
 * name, used by the raw stats table. `CHALLENGE_FIELD_LABELS` covers every
 * field except the internal FK — the fallback only fires if the interface
 * grows a field this table hasn't been updated for yet.
 */
export function challengeFieldLabel(key: string): string {
  const label = (CHALLENGE_FIELD_LABELS as Record<string, string | undefined>)[
    key
  ];

  if (label != null) {
    return label;
  }

  const spaced = key
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/([a-zA-Z])([0-9])/g, '$1 $2')
    .replace(/([0-9])([a-zA-Z])/g, '$1 $2');

  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}
